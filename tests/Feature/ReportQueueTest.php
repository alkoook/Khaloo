<?php

use App\Jobs\GenerateReportExport;
use App\Livewire\Reports\Index;
use App\Models\Partner;
use App\Models\ReportExport;
use App\Models\User;
use App\Services\ReportService;
use Illuminate\Support\Facades\Queue;
use Illuminate\Support\Facades\Storage;
use Livewire\Livewire;

test('report request queues generation and only its owner can download the finished file', function () {
    Queue::fake();
    $owner = User::factory()->create();
    $other = User::factory()->create();

    Livewire::actingAs($owner)->test(Index::class)->set('type', 'inventory')->call('download')->assertHasNoErrors();

    $export = ReportExport::query()->sole();
    expect($export->status)->toBe('pending')->and($export->path)->toBeNull();
    Queue::assertPushed(GenerateReportExport::class, 1);
    $this->actingAs($owner)->get(route('reports.exports.download', $export))->assertNotFound();

    (new GenerateReportExport($export->id))->handle(app(ReportService::class));
    $export->refresh();
    expect($export->status)->toBe('ready')->and(Storage::disk('local')->exists($export->path))->toBeTrue();
    $this->actingAs($other)->get(route('reports.exports.download', $export))->assertForbidden();
    $this->actingAs($owner)->get(route('reports.exports.download', $export))->assertOk();
    Storage::disk('local')->delete($export->path);
});

test('account statement is also generated by a job and made available privately', function () {
    Queue::fake();
    $owner = User::factory()->create();
    $partner = Partner::query()->create(['name' => 'عميل الاختبار', 'type' => Partner::TYPE_CUSTOMER]);

    Livewire::actingAs($owner)->test(Index::class)->set('partner_id', $partner->id)->call('downloadStatement')->assertHasNoErrors();

    $export = ReportExport::query()->sole();
    expect($export->kind)->toBe('statement')->and($export->status)->toBe('pending');
    Queue::assertPushed(GenerateReportExport::class, 1);
    (new GenerateReportExport($export->id))->handle(app(ReportService::class));
    $export->refresh();
    expect($export->status)->toBe('ready')->and(Storage::disk('local')->exists($export->path))->toBeTrue();
    Storage::disk('local')->delete($export->path);
});
